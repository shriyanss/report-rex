package editorconf

import (
	"fmt"
	"os"
	"path/filepath"
)

func binOrDefault(opts NvimOptions) string {
	if opts.Bin == "" {
		return "rex"
	}
	return opts.Bin
}

func passwordConfigLine(opts NvimOptions, indent string) string {
	if opts.Password != "" {
		return fmt.Sprintf("%spassword = %q,\n", indent, opts.Password)
	}
	return indent + "-- password omitted: export $REX_PASSWORD before launching nvim\n"
}

// tlsConfigLine emits the ca_cert/insecure setting that trusts rex-svr's
// self-signed certificate. Insecure wins if both are somehow set.
func tlsConfigLine(opts NvimOptions, indent string) string {
	if opts.Insecure {
		return indent + "insecure = true,\n"
	}
	if opts.CACert != "" {
		return fmt.Sprintf("%sca_cert = %q,\n", indent, opts.CACert)
	}
	return indent + "-- neither ca_cert nor insecure set: rex sync/presence will fail to connect until one is\n"
}

const standaloneEntrypointTemplate = `-- Generated by "rex editor-conf --ide nvim --standalone" -- safe to regenerate/overwrite.
vim.opt.rtp:prepend(%q)

require("rex-presence").setup({
  host = %q,
  port = %d,
  username = %q,
%s%s  bin = %q,
  dir = %q,
})

vim.o.laststatus = 2
vim.o.statusline = "%%f %%{v:lua.require('rex-presence').statusline()}"
`

func writeStandaloneEntrypoint(path, pluginDir string, opts NvimOptions) error {
	passwordLine := passwordConfigLine(opts, "  ")
	tlsLine := tlsConfigLine(opts, "  ")
	content := fmt.Sprintf(standaloneEntrypointTemplate, pluginDir, opts.Host, opts.Port, opts.Username, passwordLine, tlsLine, binOrDefault(opts), opts.Dir)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0o644)
}

const lazyPluginSpecTemplate = `-- Generated by "rex editor-conf --ide nvim" -- safe to regenerate/overwrite.
-- Loaded by lazy.nvim's lua/plugins/*.lua auto-import (LazyVim, and plain
-- lazy.nvim configs following its own recommended layout). Only activates
-- (presence + explorer highlighting + a background "rex sync") when Neovim
-- is opened inside %s -- opening it elsewhere is a no-op.
--
-- Optional: add require("rex-presence").statusline() to your own lualine
-- config to show remote presence there too -- not wired in automatically,
-- since lualine already owns 'statusline'.
return {
  dir = %q,
  name = "rex-presence",
  lazy = false,
  config = function()
    require("rex-presence").setup({
      host = %q,
      port = %d,
      username = %q,
%s%s      bin = %q,
      dir = %q,
      scoped = true,
    })
  end,
}
`

func writeLazyPluginSpec(path, pluginDir string, opts NvimOptions) error {
	passwordLine := passwordConfigLine(opts, "      ")
	tlsLine := tlsConfigLine(opts, "      ")
	content := fmt.Sprintf(lazyPluginSpecTemplate, opts.Dir, pluginDir, opts.Host, opts.Port, opts.Username, passwordLine, tlsLine, binOrDefault(opts), opts.Dir)
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0o644)
}
